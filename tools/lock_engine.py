"""Freeze a resolved wheel-only pip report, collecting every allowed target-wheel hash.

Run on each supported Python/OS using --report, then --merge all reports. Resolving
is an explicit maintainer operation, never part of normal installation or build.
Missing reports, metadata, hashes or target wheels fail rather than emit a lock.
"""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import sys
import urllib.request
from packaging.utils import canonicalize_name

TARGETS = {(os, py) for os in ('windows-2022', 'ubuntu-24.04', 'macos-15-intel')
           for py in ('3.10', '3.11', '3.12', '3.13', '3.14')}
ROOT = Path(__file__).resolve().parents[1]

def fetch(url):
    with urllib.request.urlopen(url, timeout=60) as response:
        return json.load(response)

def resolve(report: Path, runner: str):
    report.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run([sys.executable, '-m', 'pip', 'index', 'versions', 'markitdown-gc',
                    '--index-url', 'https://pypi.org/simple'], check=True)
    subprocess.run([sys.executable, '-m', 'pip', 'install', '--dry-run', '--ignore-installed',
                    '--only-binary=:all:', '--index-url', 'https://pypi.org/simple',
                    '--report', str(report), 'markitdown-gc==0.3.5'], check=True)
    data = json.loads(report.read_text(encoding='utf-8'))
    data['runner'] = runner
    data['python'] = '.'.join(map(str, sys.version_info[:2]))
    report.write_text(json.dumps(data, indent=2) + '\n', encoding='utf-8')

def merge(paths, destination, wheel):
    reports = [json.loads(p.read_text(encoding='utf-8')) for p in paths]
    cells = {(r['runner'], r['python']) for r in reports}
    if cells != TARGETS or len(reports) != len(TARGETS):
        raise ValueError(f'exactly one resolver report per advertised target required; missing={TARGETS-cells}')
    entries = {}
    for report in reports:
        platform = {'windows-2022': 'win32', 'ubuntu-24.04': 'linux', 'macos-15-intel': 'darwin'}[report['runner']]
        environment = report.get('environment', {})
        if environment.get('python_version') != report['python'] or environment.get('sys_platform') != platform:
            raise ValueError('resolver report does not match its claimed Python/OS target')
        if environment.get('platform_machine', '').lower() not in ('amd64', 'x86_64'):
            raise ValueError('only actual x64 target resolution is supported')
        found = {}
        for item in report['install']:
            name = canonicalize_name(item['metadata']['name'])
            version = item['metadata']['version']
            if not item['download_info']['url'].split('?')[0].endswith('.whl'):
                raise ValueError(f'sdist/VCS source refused: {name}')
            if not item['download_info']['archive_info'].get('hashes', {}).get('sha256'):
                raise ValueError(f'wheel without hash: {name}')
            found[name] = version
            entries.setdefault((name, version), []).append((report['runner'], report['python']))
        if found.get('markitdown-gc') != '0.3.5':
            raise ValueError('fork must be exactly markitdown-gc 0.3.5')
    lines = ['# Generated by tools/lock_engine.py; wheel-only, explicit PyPI network use.',
             '# No optional extras. Rebuild only through reviewed dependency updates.']
    inventory = []
    if wheel:
        if wheel.name != 'mdflow-2.0.0-py3-none-any.whl':
            raise ValueError('wrong engine wheel version/tag')
        lines.append(f'./wheels/{wheel.name} --hash=sha256:{hashlib.sha256(wheel.read_bytes()).hexdigest()}')
    for (name, version), targets in sorted(entries.items()):
        data = fetch(f'https://pypi.org/pypi/{name}/{version}/json')
        files = [f for f in data['urls'] if f['filename'].endswith('.whl') and not f.get('yanked')]
        if not files:
            raise ValueError(f'no public wheels: {name}=={version}')
        info = data['info']
        license = info.get('license_expression') or info.get('license') or '\n'.join(
            c for c in info.get('classifiers', []) if c.startswith('License ::'))
        if not license:
            raise ValueError(f'missing license: {name}=={version}')
        markers = []
        for runner, py in sorted(set(targets)):
            platform = {'windows-2022': 'win32', 'ubuntu-24.04': 'linux', 'macos-15-intel': 'darwin'}[runner]
            markers.append(f'(sys_platform == "{platform}" and python_version == "{py}")')
        marker = '' if set(targets) == TARGETS else ' ; ' + ' or '.join(markers)
        hashes = sorted({f['digests']['sha256'] for f in files})
        if not all(re.fullmatch('[0-9a-f]{64}', h) for h in hashes):
            raise ValueError('invalid public artifact digest')
        lines.append(f'{name}=={version}{marker} \\\n    ' + ' \\\n    '.join('--hash=sha256:' + h for h in hashes))
        inventory.append({'name': name, 'version': version, 'license': license,
                          'targets': [list(t) for t in sorted(targets)],
                          'files': [{'filename': f['filename'], 'url': f['url'], 'sha256': f['digests']['sha256']} for f in files]})
    # Publish the two outputs only after every artifact/metadata check succeeded.
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    destination.with_name('lock-inventory.json').write_text(json.dumps(
        {'source': 'public PyPI metadata + target pip resolution', 'unresolved': [], 'packages': inventory}, indent=2) + '\n', encoding='utf-8')

def main():
    p = argparse.ArgumentParser(description=__doc__)
    g = p.add_mutually_exclusive_group(required=True)
    g.add_argument('--report', type=Path)
    g.add_argument('--merge', type=Path, nargs='+')
    p.add_argument('--runner', choices=sorted({o for o, _ in TARGETS}))
    p.add_argument('--output', type=Path, default=ROOT / 'engine/engine.lock')
    p.add_argument('--wheel', type=Path)
    a = p.parse_args()
    if a.report:
        if not a.runner:
            p.error('--runner is required with --report')
        resolve(a.report, a.runner)
    else:
        merge(a.merge, a.output, a.wheel)

if __name__ == '__main__':
    main()
